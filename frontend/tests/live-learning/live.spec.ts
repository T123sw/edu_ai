test('shared classroom joins with isolated progress, conversations and playable real material', async ({ page, request }) => {
  const owner = { Authorization: `Bearer ${fixture.teacher.token}` }, student = { Authorization: `Bearer ${fixture.student.token}` };
  const url = `${api}/api/self-learning/courses/${course}`;
  expect((await request.post(url + '/publish', { headers: student })).status()).toBeGreaterThanOrEqual(400);
  expect((await request.post(url + '/publish', { headers: owner })).status()).toBe(200);
  await page.goto('/');
  await page.getByLabel('账号').fill(fixture.student.user.username);
  await page.getByLabel('密码', { exact: true }).fill(fixture.student.password);
  await page.getByRole('button', { name: /^登\s*录$/ }).click();
  await page.locator('.sl-class-card').filter({ hasText: fixture.room.title }).last().click();
  await expect(page.getByRole('heading', { name: '课堂目录' })).toBeVisible();
  const room = await (await request.get(url, { headers: student })).json();
  expect(room.messages).toHaveLength(0);
  expect(Object.values(room.progress).some((p: any) => p.note?.includes('真实接口笔记'))).toBe(false);
  const first = room.chapters[0].resources.find((r: any) => r.remote?.materialType === 'classroom');
  await page.goto(`/#/classroom/${course}?resource=${first.id}`);
  const player = page.frameLocator('.sl-live-material');
  await expect(player.getByRole('button', { name: '下一页', exact: true })).toBeVisible({ timeout: 60000 });
  const counter = player.locator('.classroom-page-count');
  for (let i = 0; i < 3; i++) {
    const number = Number((await counter.innerText()).split('/')[0].trim());
    if (number === 1) break;
    await player.getByRole('button', { name: '上一页', exact: true }).click();
    await expect(counter).toContainText(`${number - 1} /`);
  }
  await expect(counter).toContainText('1 /');
  await player.getByRole('button', { name: '下一页', exact: true }).click();
  await expect(player.locator('.classroom-page-count')).toContainText('2 /');
  await expect.poll(async () => (await (await request.get(url, { headers: student })).json()).progress[first.id]?.position).toBe(1);
  await page.reload();
  await expect(player.locator('.classroom-playback-surface')).toBeVisible();
  await expect(player.locator('.classroom-page-count')).toContainText('2 /');
  await expect.poll(async () => (await (await request.get(url, { headers: student })).json()).progress[first.id]?.position).toBe(1);
  const material = await (await request.get(`${api}/api/courses/${course}/classrooms/${first.id}`, { headers: student })).json();
  const audio = material.scenes.flatMap((s: any) => s.actions || []).find((a: any) => a.audioUrl)?.audioUrl;
  expect(audio).toBeTruthy();
  const audioResponse = await request.get(api + audio, { headers: student });
  expect(audioResponse.status()).toBe(200);
  expect(audioResponse.headers()['content-type']).toContain('audio/');
  expect((await audioResponse.body()).length).toBeGreaterThan(1000);
  const personal = fixture.room.chapters[0].id;
  expect((await request.post(url + `/topics/${personal}/turns`, { headers: student, data: { resource_id: 'someone-elses-resource', question: '测试', request_id: crypto.randomUUID() } })).status()).toBe(422);
});


test('homepage creates a real classroom and durable jobs from the learning goal', async ({ page, request }) => {
  await page.goto('/');
  await page.getByLabel('账号').fill(fixture.teacher.user.username);
  await page.getByLabel('密码', { exact: true }).fill(fixture.teacher.password);
  await page.getByRole('button', { name: /^登\s*录$/ }).click();
  await page.getByRole('textbox', { name: '学习知识点与目标' }).fill('用两个知识点学习二进制计数。请做极简讲解，每页只讲一句话。');
  const response = page.waitForResponse(r => r.url().endsWith('/api/self-learning/courses') && r.request().method() === 'POST', { timeout: 150000 });
  await page.getByRole('button', { name: '开始学习', exact: true }).click();
  const result = await response;
  expect(result.status()).toBe(202);
  const room = await result.json();
  await expect(page).toHaveURL(new RegExp(`/classroom/${room.id}`));
  await expect(page.getByRole('heading', { name: '课堂目录' })).toBeVisible();
  const headers = { Authorization: `Bearer ${fixture.teacher.token}` };
  const duplicate = await request.post(`${api}/api/self-learning/courses`, { headers, data: JSON.parse(result.request().postData()!) });
  expect(duplicate.status()).toBe(202);
  expect((await duplicate.json()).id).toBe(room.id);
  const state = await (await request.get(`${api}/api/self-learning/state`, { headers })).json();
  expect(state.rooms.filter((r: any) => r.id === room.id)).toHaveLength(1);
  expect(state.serverJobs.filter((j: any) => j.course_id === room.id)).toHaveLength(room.chapters.length);
});


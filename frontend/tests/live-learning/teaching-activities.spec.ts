import { test, expect } from 'playwright/test';

test('draft and saved answer stay bound to explicit tutoring requests', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('edu-ai-auth', JSON.stringify({ token: 'alice', user: { username: 'alice', role: 'student' } })));
  await page.goto('/#/classroom/learning-fixture?resource=a-quiz');
  const frame = page.frameLocator('iframe.sl-live-material');
  const first = frame.locator('[data-quiz-question="0"]');
  const second = frame.locator('[data-quiz-question="1"]');
  await first.getByRole('checkbox', { name: '6', exact: true }).check();
  await page.reload();
  await expect(first.getByRole('checkbox', { name: '6', exact: true })).toBeChecked();
  await first.getByRole('button', { name: '提示', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '向学习 Agent 提问' })).toHaveValue(/只给下一步提示/);
  const send = page.waitForRequest(r => r.url().endsWith('/agent-turns') && r.method() === 'POST');
  await page.getByRole('button', { name: '发送问题' }).click();
  const draft = (await send).postDataJSON().reading_context;
  expect(draft.practice.draft.option_ids).toEqual(['option_2']);
  expect(draft.practice.attempt_id).toBeUndefined();
  await expect(page.getByRole('log').getByText(/已回答：请结合我当前的作答/)).toBeVisible();
  await expect(first.getByRole('checkbox', { name: '作答后继续辅导', exact: true })).toHaveCount(0);
  await first.getByRole('button', { name: '提交答案', exact: true }).click();
  await expect(first.getByRole('group', { name: '已保存的作答' }).getByRole('checkbox', { name: '6', exact: true })).toBeChecked();
  await expect(page.getByRole('log').getByText(/已回答：请根据我刚提交/)).toHaveCount(0);
  await expect(page.getByRole('note', { name: '已引用报告片段' })).toContainText('已引用这次提交的作答');
  await page.getByRole('textbox', { name: '向学习 Agent 提问' }).fill('这次回答的问题在哪里？');
  const followUp = page.waitForRequest(r => r.url().endsWith('/agent-turns') && r.method() === 'POST');
  await page.getByRole('button', { name: '发送问题' }).click();
  const followUpContext = (await followUp).postDataJSON().reading_context;
  expect(followUpContext.practice.attempt_id).toBeTruthy();
  expect(followUpContext.practice.draft).toBeUndefined();
  await expect(page.getByRole('log').getByText('已回答：这次回答的问题在哪里？')).toBeVisible();
  await first.getByRole('button', { name: '讲解', exact: true }).click();
  const saved = page.waitForRequest(r => r.url().endsWith('/agent-turns') && r.method() === 'POST');
  await page.getByRole('button', { name: '发送问题' }).click();
  const snapshot = (await saved).postDataJSON().reading_context;
  expect(snapshot.practice.attempt_id).toBeTruthy();
  expect(snapshot.practice.draft).toBeUndefined();
  await expect(page.getByRole('log').getByText(/已回答：请结合我这次已提交/)).toBeVisible();
  await second.getByRole('button', { name: '提示', exact: true }).click();
  const next = page.waitForRequest(r => r.url().endsWith('/agent-turns') && r.method() === 'POST');
  await page.getByRole('button', { name: '发送问题' }).click();
  const nextSnapshot = (await next).postDataJSON().reading_context;
  expect(nextSnapshot.locator.question_index).toBe(1);
  expect(nextSnapshot.practice.check_id).not.toBe(snapshot.practice.check_id);
  expect(nextSnapshot.practice.attempt_id).toBeUndefined();
  await page.reload();
  await expect(first.getByRole('checkbox', { name: '作答后继续辅导', exact: true })).toHaveCount(0);
  await expect(second.getByRole('checkbox', { name: '作答后继续辅导', exact: true })).toHaveCount(0);
  await expect(first.getByRole('group', { name: '已保存的作答' }).getByRole('checkbox', { name: '6', exact: true })).toBeChecked();
  await expect(page.getByRole('log').getByText(/已回答：请根据我刚提交/)).toHaveCount(0);
});
